"""Builds REPORT.pdf (<= 3 pages) from the CSVs and figures in outputs/task1/.

Every number in the report is read from a result file here, not typed in, so the PDF is
regenerated by `python main.py` together with the results it describes.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
from reportlab.lib import colors
from reportlab.lib.enums import TA_JUSTIFY
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import (Image, KeepTogether, PageBreak, Paragraph, SimpleDocTemplate,
                                Spacer, Table, TableStyle)
from scipy.stats import binom, wilcoxon

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs" / "task1"


def _img(path: Path, width_cm: float) -> Image:
    from PIL import Image as PILImage
    w, h = PILImage.open(path).size
    return Image(str(path), width=width_cm * cm, height=width_cm * cm * h / w)


def _table(rows, col_w, style):
    t = Table(rows, colWidths=[w * cm for w in col_w])
    t.setStyle(TableStyle([
        ("FONT", (0, 0), (-1, -1), "Helvetica", 7.3),
        ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 7.3),
        ("LINEBELOW", (0, 0), (-1, 0), 0.5, colors.black),
        ("LINEBELOW", (0, -1), (-1, -1), 0.5, colors.black),
        ("TOPPADDING", (0, 0), (-1, -1), 1), ("BOTTOMPADDING", (0, 0), (-1, -1), 1),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE")]))
    return t


def numbers() -> dict:
    n = {}
    audit = pd.read_csv(OUT / "audit.csv")
    kept = audit[audit.action != "exclude"]
    n["n_kept"], n["excluded"] = len(kept), audit.loc[audit.action == "exclude", "subject"].tolist()
    n["n_left"], n["n_right"] = int(kept.usable_left.sum()), int(kept.usable_right.sum())
    n["interp"] = audit.loc[audit.action == "keep_interp", "subject"].tolist()

    a2 = pd.read_csv(OUT / "a2_lateralisation.csv")
    n["present"] = a2.loc[a2.label == "present", "subject"].tolist()
    n["mu_uncorr"] = int((a2.p_mu < 0.05).sum())
    n["li_w_p"] = wilcoxon(a2.li_mu_db, alternative="greater").pvalue
    n["li_median"] = a2.li_mu_db.median()
    ref = pd.read_csv(OUT / "a2_reference_check.csv")
    n["ref_present"] = {r: int((ref[f"label_{r}"] == "present").sum()) for r in ["as_recorded", "average", "csd"]}
    n["ref_changed"] = int((ref.label_csd != ref.label_as_recorded).sum())
    n["examples"] = sorted(p.name for p in OUT.glob("a2_tf_S*.png"))

    n["a3"] = pd.read_csv(OUT / "a3_summary.csv").set_index("route")
    tab = pd.read_csv(OUT / "per_subject_table.csv")
    n["thr_range"] = (tab.chance_threshold.min(), tab.chance_threshold.max())
    n["absent_ocular"] = int(((tab.label == "absent") & (tab.acc_ocular >= tab.chance_threshold)).sum())
    n["n_absent"] = int((tab.label == "absent").sum())

    n["params"] = pd.read_csv(OUT / "b1_params.csv")
    split = pd.read_csv(OUT / "split.csv")
    n["split"] = {k: sorted(split.loc[split.set == k, "subject"].tolist()) for k in ["train", "val", "test"]}
    runs = pd.read_csv(OUT / "b2_runs.csv").set_index("run_id")
    n["runs"] = runs
    t = pd.read_csv(OUT / "per_subject_table.csv").set_index("subject")
    n["n_test_trials"] = int((t.n_left + t.n_right).loc[n["split"]["test"]].sum())
    cm_ = pd.read_csv(OUT / "b2_2_common_mode.csv")
    n["cm"] = dict(mean=cm_.common_mode_LminusR_uV.mean(), pos=int((cm_.common_mode_LminusR_uV > 0).sum()),
                   n=len(cm_), f7=cm_.F7_LminusR_uV.mean(), f8=cm_.F8_LminusR_uV.mean())
    tdel = pd.read_csv(OUT / "b2_3_token_deletion.csv").groupby(["kind", "k"]).acc.mean()
    n["tdel"] = tdel
    gdel = pd.read_csv(OUT / "b2_3_group_deletion.csv").groupby(["model", "group"]).acc.mean()
    n["gdel"] = gdel
    n["corr"] = pd.read_csv(OUT / "b2_3_correlations.csv").set_index(["model", "part_a_measure"])
    n["xs"] = pd.read_csv(OUT / "b2_3_cross_subject_route_decoders.csv")
    post = pd.read_csv(OUT / "b2_3_heog_regressed_per_subject.csv")
    n["post"] = post
    shares = pd.read_csv(OUT / "b2_3_attribution_shares.csv")
    n["shares"] = shares
    return n


def build(path: Path = ROOT / "REPORT.pdf") -> None:
    N = numbers()
    a3, runs, gdel, corr = N["a3"], N["runs"], N["gdel"], N["corr"]
    T = lambda rid: runs.loc[rid, "test_acc"] * 100
    V = lambda rid: runs.loc[rid, "val_acc"] * 100
    thr = binom.ppf(0.95, N["n_test_trials"], 0.5) / N["n_test_trials"] * 100
    xs = N["xs"].groupby("route").apply(lambda g: (g.acc * g.n).sum() / g.n.sum() * 100)
    # Pooled over test trials, like every other accuracy in the report.
    post = pd.Series({m: gdel.loc[(m, "HEOG regressed (post-hoc)")] * 100 for m in ["transformer", "EEGNet"]})
    tok = lambda kind, k: N["tdel"].loc[(kind, k)] * 100
    sh = N["shares"].set_index(["model", "group"]).share
    t_early = {m: sum(sh.loc[(m, f"time {a:.2f}-{a + 0.25:.2f}s")] for a in np.arange(0.25, 1.5, 0.25)) * 100
               for m in ["transformer", "EEGNet"]}

    ss = getSampleStyleSheet()
    body = ParagraphStyle("b", parent=ss["Normal"], fontName="Helvetica", fontSize=8.2, leading=10.0,
                          alignment=TA_JUSTIFY, spaceAfter=3)
    h1 = ParagraphStyle("h1", parent=body, fontName="Helvetica-Bold", fontSize=13, leading=15, spaceAfter=2)
    h2 = ParagraphStyle("h2", parent=body, fontName="Helvetica-Bold", fontSize=9.5, leading=11.5,
                        spaceBefore=4, spaceAfter=2)
    cap = ParagraphStyle("c", parent=body, fontSize=7.0, leading=8.4, textColor=colors.HexColor("#333333"))
    P = lambda t, s=body: Paragraph(t, s)

    s = []
    s.append(P("Motor imagery on PhysioNet EEGBCI (S70–S109): what is in the signal, and what do the networks learn?", h1))
    s.append(P("All numbers and figures are produced by <font face='Courier'>python main.py</font> (seed 42); "
               "choices with alternatives are in DECISIONS.md, predictions (committed before results) in PREDICTIONS.md.", cap))

    s.append(P("A1 — Data audit", h2))
    s.append(P(f"Runs 4, 8, 12 (imagined left/right fist; T1 = left, T2 = right, T0 = rest — PhysioNet EEGMMIDB protocol page, "
               f"confirmed in the EDF annotations). <font face='Courier'>audit.csv</font> lists, per subject, runs, sampling rate, "
               f"trial counts, event mapping, anomalies and the action taken; the script refuses to run if an anomaly has no explicit decision. "
               f"Excluded: S{', S'.join(map(str, N['excluded']))} (128 Hz with a different cue/rest timing — 1.38 s rest leaves no pre-cue baseline). "
               f"Kept with fixes: dead/noisy channels interpolated in S{', S'.join(map(str, N['interp']))}; truncated run 8 of S104 and "
               f"13 end-of-run trials whose window does not fit dropped. Result: {N['n_kept']} subjects, {N['n_left']} left / {N['n_right']} right trials."))

    s.append(P("A2 — Physiological ground truth", h2))
    s.append(P(f"<b>Reference.</b> Every channel is 'electrode minus an undocumented reference'; whatever the reference picks up "
               f"appears in C3 and C4 alike, and if it lies off the midline or over sensorimotor cortex it can create or cancel a C3–C4 difference. "
               f"We use a surface Laplacian (CSD), which is reference-free and local. Mu-lateralised ERD is 'present' in "
               f"{N['ref_present']['as_recorded']}/{N['n_kept']} subjects as recorded, {N['ref_present']['average']} with common average and "
               f"{N['ref_present']['csd']} with CSD ({N['ref_changed']} labels change). <b>Method.</b> Morlet power (4–35 Hz) at C3/C4 and "
               f"neighbours; per-trial ERD = 10·log10(power 0.5–3.5 s / power −1.5 to −0.5 s), a baseline inside the 4.1 s rest that ends "
               f"0.5 s before the cue and starts after the previous trial's beta rebound. LI = mean(ERD<sub>C3</sub>−ERD<sub>C4</sub> | left) − "
               f"mean(… | right) in the mu band (positive = contralateral); one-sided label-permutation test (5000), BH-FDR over subjects. "
               f"<b>Result.</b> Present in {len(N['present'])}/{N['n_kept']} (S{', S'.join(map(str, N['present']))}); {N['mu_uncorr']} at uncorrected p &lt; .05; "
               f"group median LI {N['li_median']:+.2f} dB (Wilcoxon p = {N['li_w_p']:.3f}). Contralateral ERD is real on average but reliable "
               f"in few individuals; many 'absent' subjects show bilateral, non-lateralised ERD (e.g. S082 below)."))
    s.append(_img(OUT / "a2_summary.png", 17.5))
    ex = N["examples"]
    grid = Table([[_img(OUT / ex[i], 8.6) for i in (0, 1)], [_img(OUT / ex[i], 8.6) for i in (2, 3)]],
                 colWidths=[8.8 * cm, 8.8 * cm])
    grid.setStyle(TableStyle([("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                              ("TOPPADDING", (0, 0), (-1, -1), 0), ("BOTTOMPADDING", (0, 0), (-1, -1), 0)]))
    s.append(grid)
    s.append(P("Fig. 1. Top: per-subject mu vs beta LI and grand-average contralateral/ipsilateral ERD (CSD). Bottom: CSD time–frequency "
               "maps (dB vs baseline) at C3/C4 for two 'present' and two 'absent' subjects, chosen by rule (strongest/weakest significant; "
               "closest to significance/clearest null).", cap))

    s.append(P("A3 — Confound check", h2))
    s.append(P(f"The cue is a target on the <i>left or right of the screen</i> for ~4 s, with no documented fixation instruction, so the "
               f"label is confounded with stimulus position. Routes: (1) <b>eye movements</b> towards the target — horizontal-EOG proxies "
               f"F7−F8, AF7−AF8, Fp1−Fp2, 0.1–8 Hz, 0–3.5 s; (2) <b>lateralised visual response</b> — PO7−PO8, PO3−PO4, O1−O2 at 0.05–0.5 s "
               f"(evoked) and CSD posterior alpha 0.5–3.5 s. Control: CSD sensorimotor mu/beta. Within-subject shrinkage LDA, leave-one-run-out CV. "
               f"Chance threshold per subject: smallest k with P(X ≥ k | n, 0.5) ≤ .05 (binomial; {N['thr_range'][0] * 100:.1f}–"
               f"{N['thr_range'][1] * 100:.1f}% for n = 42–45); by chance ≈ 1.9/37 subjects pass."))
    rows = [["route", "mean acc", "subjects ≥ threshold", "Wilcoxon p (vs 50%)"]]
    labels = {"ocular": "eye movement (HEOG proxies)", "visual_evoked": "visual evoked", "visual_alpha": "posterior alpha",
              "motor": "motor control (mu/beta, CSD)", "ocular_presaccade": "eye, 0.05–0.15 s (post-hoc)",
              "visual_presaccade": "visual, 0.05–0.15 s (post-hoc)"}
    for r, lab in labels.items():
        x = a3.loc[r]
        pw = "< 0.001" if x.p_wilcoxon_vs_50 < 0.001 else f"{x.p_wilcoxon_vs_50:.2g}"
        rows.append([lab, f"{x.mean_acc * 100:.1f}%", f"{int(x.n_above)}/{int(x.n_subjects)}", pw])
    s.append(_table(rows, [5.5, 2.0, 3.2, 3.2], None))
    s.append(Spacer(1, 3))
    s.append(P(f"<b>Outcome.</b> I predicted the eye route would win but badly underestimated it: subjects look at the target "
               f"(±45 µV F7−F8 step of opposite polarity from ~0.2 s, Fig. 2). It decodes left/right in {int(a3.loc['ocular'].n_above)}/37 subjects, "
               f"including {N['absent_ocular']} of the {N['n_absent']} A2-absent ones, against {int(a3.loc['motor'].n_above)}/37 for the motor route. The 'visual' "
               f"decoder's peak coincides with the saccade; restricted to the pre-saccadic window it falls to chance, so it is mostly the same eye movement."))
    s.append(_img(OUT / "a3_evidence.png", 17.5))
    s.append(P("Fig. 2. Grand-average F7−F8 and PO7−PO8 for left/right targets (±SEM, 37 subjects); per-subject accuracies with thresholds "
               "(green = A2 present).", cap))

    s.append(P("B — Networks", h2))
    p = N["params"].set_index("tokeniser").params
    s.append(P(f"Fixed seeded subject split: train {len(N['split']['train'])}, validation {len(N['split']['val'])} (early stopping only), "
               f"test {len(N['split']['test'])} (S{', S'.join(map(str, N['split']['test']))}); per-channel z-score from training subjects; input 64 ch × 0–4 s, 1–40 Hz. "
               f"<b>EEGNet-8,2</b> ({int(N['params'].set_index('model').params.loc['EEGNet'])} params) adapted to 160 Hz: temporal kernel 64→80 (0.5 s), "
               f"separable kernel 16→20 (500 ms at 40 Hz); dropout 0.25 (cross-subject). <b>Transformer</b>: tokeniser → 2 pre-norm layers (d = 16) → mean pool; "
               f"time-patch tokens (spatial projection 64→8, 2 temporal filters per virtual channel, 250 ms patches, {int(p.loc['time'])} params), channel tokens "
               f"with/without a learned electrode-identity embedding ({int(p.loc['chan_id'])}/{int(p.loc['chan_noid'])}); all ≤ 2.34× EEGNet. "
               f"{N['n_test_trials']} test trials: chance threshold {thr:.1f}%, SE ≈ 2.4 points."))
    rows = [["run", "subj.", "val", "test"],
            *[[lab, str(int(runs.loc[r, 'n_train_subjects'])), f"{V(r):.1f}%", f"{T(r):.1f}%"] for lab, r in [
                ("EEGNet", "eegnet_n5"), ("EEGNet", "eegnet_n20"), ("EEGNet", "eegnet_nall"),
                ("TF time-patch", "tf-time_n5"), ("TF time-patch", "tf-time_n20"),
                ("TF time-patch", "tf-time_nall"), ("TF channel + id", "tf-chan_id_nall"),
                ("TF channel, no id", "tf-chan_noid_nall"),
                ("TF time, stop acc*", "tf-time_nall_stopacc"),
                ("TF chan + id, stop acc*", "tf-chan_id_nall_stopacc")]]]
    rows.append(["* post-hoc (D28)", "", "", ""])
    tbl = _table(rows, [3.9, 1.0, 1.1, 1.1], None)
    fig_b = _img(OUT / "b2_scaling_tokenisation.png", 10.0)
    side = Table([[tbl, fig_b]], colWidths=[7.4 * cm, 10.2 * cm])
    side.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 0)]))
    s.append(side)
    s.append(P(f"<b>B2.1.</b> EEGNet is flat at {T('eegnet_n5'):.1f}/{T('eegnet_n20'):.1f}/{T('eegnet_nall'):.1f}% for 5/20/all subjects; the "
               f"transformer rises {T('tf-time_n5'):.1f} → {T('tf-time_n20'):.1f} → {T('tf-time_nall'):.1f}%. <b>B2.2.</b> With validation-loss stopping "
               f"(pre-registered) channel + identity stopped at epoch 1 (validation loss rose from the start while accuracy improved); stopping on "
               f"validation accuracy gives {T('tf-chan_id_nall_stopacc'):.1f}% vs {T('tf-time_nall_stopacc'):.1f}% for time patches. Channel tokens without "
               f"identity: {T('tf-chan_noid_nall'):.1f}% (above chance, p ≈ .001). <b>B2.3</b> (best transformer by validation accuracy: time-patch, "
               f"stop on accuracy; Integrated Gradients, Fig. 3): deleting the top-2/top-8 attributed 250 ms tokens gives {tok('most-attributed', 2):.1f}/"
               f"{tok('most-attributed', 8):.1f}% vs {tok('random', 2):.1f}/{tok('random', 8):.1f}% for random tokens (weakly faithful). "
               f"{t_early['transformer']:.0f}% (transformer) and {t_early['EEGNet']:.0f}% (EEGNet) of attribution falls in 0.25–1.5 s (31% if uniform). "
               f"Zeroing the 17 frontal channels: transformer {gdel.loc[('transformer', 'frontal/ocular')] * 100:.1f}%, EEGNet "
               f"{gdel.loc[('EEGNet', 'frontal/ocular')] * 100:.1f}%; sensorimotor: {gdel.loc[('transformer', 'sensorimotor')] * 100:.1f}% / "
               f"{gdel.loc[('EEGNet', 'sensorimotor')] * 100:.1f}%. Regressing the HEOG proxies out of every channel (coefficients from training "
               f"subjects; post-hoc): transformer {post.loc['transformer']:.1f}%, EEGNet {post.loc['EEGNet']:.1f}%. Per test subject (n = 10), transformer "
               f"accuracy tracks A3 ocular accuracy (ρ = {corr.loc[('transformer', 'acc_ocular'), 'spearman_rho']:+.2f}, p = "
               f"{corr.loc[('transformer', 'acc_ocular'), 'p']:.2f}), not mu LI (ρ = {corr.loc[('transformer', 'li_mu_db'), 'spearman_rho']:+.2f}); EEGNet: "
               f"ocular ρ = {corr.loc[('EEGNet', 'acc_ocular'), 'spearman_rho']:+.2f}, LI ρ = {corr.loc[('EEGNet', 'li_mu_db'), 'spearman_rho']:+.2f} "
               f"(p = {corr.loc[('EEGNet', 'li_mu_db'), 'p']:.2f}). All 10 test subjects are A2-absent (random split), which limits the LI correlation. "
               f"<b>Conclusion:</b> the transformer reads the A3 ocular confound and nothing else we can detect; EEGNet reads it for about half of its "
               f"above-chance accuracy, with an unresolved remainder."))
    s.append(_img(OUT / "b2_3_reliance.png", 17.5))
    s.append(P("Fig. 3. B2.3: IG deletion test; attribution over time and per channel; per-region attribution; channel-group deletion and "
               "HEOG regression; per-test-subject accuracy vs A3 ocular accuracy and A2 mu LI.", cap))

    # ---- write-up (<= 1 page) ----
    w = []
    w.append(P("Write-up", h2))
    w.append(P(f"<b>(a) If a model scores 70% on these subjects, how much of that could be explained without motor imagery?</b> "
               f"Potentially all of it. Eye movements towards the cued side alone decode left/right at {a3.loc['ocular'].mean_acc * 100:.0f}% within "
               f"subject ({int(a3.loc['ocular'].n_above)}/37 subjects above chance) and at <b>{xs.loc['ocular']:.1f}%</b> across subjects — an LDA on "
               f"three frontal bipolar derivations trained on the 23 training subjects and tested on the 10 test subjects, i.e. above 70% with no "
               f"sensorimotor channel at all. The motor route on the same subjects reaches {a3.loc['motor'].mean_acc * 100:.1f}% within subject "
               f"({int(a3.loc['motor'].n_above)}/37) and {xs.loc['motor']:.1f}% across subjects; lateralised mu ERD is significant in only "
               f"{len(N['present'])}/37 subjects. The networks confirm it: removing the HEOG component at test time takes the transformer from "
               f"{T('tf-time_nall_stopacc'):.1f}% to {post.loc['transformer']:.1f}% (chance) and EEGNet from {T('eegnet_nall'):.1f}% to "
               f"{post.loc['EEGNet']:.1f}%. So of a 70% score (20 points above chance), the ocular route can supply all 20; for our EEGNet, "
               f"at least {T('eegnet_nall') - post.loc['EEGNet']:.0f} of its {T('eegnet_nall') - 50:.0f} points above chance are ocular and the "
               f"rest is unattributed. A credible motor-imagery claim on this dataset needs ocular control (fixation, EOG regression or ICA, or a "
               f"window and channel set shown to carry no HEOG) and a comparison against this confound baseline, not against 50%."))
    w.append(P(f"<b>(b) Mechanistic explanation of B2.</b> <i>Scaling.</i> The decisive feature is one large, slow potential with the same "
               f"polarity in nearly every subject. EEGNet's first two layers are a temporal filter followed by one spatial filter per temporal "
               f"filter (depthwise weights, one per electrode): a single low-pass temporal filter plus a spatial filter ≈ F7−F8 is exactly the "
               f"HEOG decoder, so ~225 trials from 5 subjects suffice and more subjects add nothing ({T('eegnet_n5'):.1f} → {T('eegnet_nall'):.1f}%). "
               f"<b>This contradicted my prediction</b> of a rising EEGNet curve: I expected a cross-subject problem to need many subjects, but "
               f"the confound is easier to share across people than ERD. The transformer has no such built-in structure — its spatial projection, "
               f"temporal filters and attention are learned jointly — and it is at chance with 5 subjects, reaching {T('tf-time_nall'):.1f}% with 23. "
               f"<i>Tokenisation.</i> Time-patch tokens encode electrode identity in the spatial-projection weights (one weight per electrode per "
               f"virtual channel); channel tokens only through the learned identity embedding. Without it, a shared token encoder, attention and "
               f"mean pooling make the model exactly invariant to permuting electrodes: it cannot represent any C3-vs-C4 or F7-vs-F8 contrast, so "
               f"lateralised ERD is unusable. I predicted chance; <b>it scored {T('tf-chan_noid_nall'):.1f}%, contradicting me</b>, because the eye "
               f"potential is not mirror-symmetric: during the saccade left-minus-right is {N['cm']['f7']:+.1f} µV at F7 but {N['cm']['f8']:+.1f} µV at F8, "
               f"and the mean over all 64 channels shifts by {N['cm']['mean']:+.1f} µV ({N['cm']['pos']}/{N['cm']['n']} subjects) — what an off-midline "
               f"recording reference would produce, the same undocumented reference A2 had to work around. An order-blind model reads that global "
               f"shift. <i>Reliance.</i> The transformer's evidence sits in the frontal channels (zeroing them: chance) and in the HEOG component "
               f"(regressing it out: chance). EEGNet survives zeroing any one region because the eye potential volume-conducts to temporal "
               f"(FT7/T7 as large as F7) and, through the reference, all channels; its depthwise spatial filters can pick it up anywhere, so "
               f"only removing the component itself costs it {T('eegnet_nall') - post.loc['EEGNet']:.0f} points. Token deletion was only weakly "
               f"faithful because the 41-sample temporal filters straddle 40-sample token boundaries and the saccade spans several tokens."))
    s.append(KeepTogether(w))
    doc = SimpleDocTemplate(str(path), pagesize=A4, leftMargin=1.5 * cm, rightMargin=1.5 * cm,
                            topMargin=1.2 * cm, bottomMargin=1.2 * cm, title="EEG motor imagery report",
                            author="")
    doc.build(s)


def main() -> None:
    build()
    print(f"[report] wrote {ROOT / 'REPORT.pdf'}")


if __name__ == "__main__":
    main()
